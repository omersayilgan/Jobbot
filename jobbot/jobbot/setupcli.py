"""`setup.py` — read someone's documents and generate their whole configuration.

The tool ships with no personal data. This turns a folder of documents into a
profile: which skill domains the person actually has evidence for, how postings
should be scored against them, which subjects their transcripts say they are
good at, what their cover letters should claim, and where to search.

    python3 setup.py                       # read ./documents (and the parent folder)
    python3 setup.py --documents ~/papers  # read somewhere else
    python3 setup.py --preset munich-deeptech
    python3 setup.py --regenerate          # rebuild configs from an edited profile.yaml
    python3 setup.py --list                # show profiles
    python3 setup.py --use anna-schmidt    # switch the active profile
"""
